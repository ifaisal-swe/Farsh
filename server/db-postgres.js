'use strict';
/**
 * PostgreSQL behind the same synchronous interface as node:sqlite (prepare().get/all/run, exec, close), so the trading
 * code path is identical on both. Queries run in a worker thread while this thread waits (Atomics.wait): use it ONLY
 * in a process that serves one customer (server/saas/tenant.js).
 *
 * - one connection, guarded by an advisory lock: two processes can never write the same account
 * - a lost connection outside a transaction is reopened for the next statement
 * - a lost connection or timeout INSIDE a transaction ends it; if that happens during COMMIT the outcome is unknown,
 *   so onFatal() is called (the process exits and restarts from what the database really contains)
 */
const { Worker, MessageChannel, receiveMessageOnPort } = require('node:worker_threads');
const path = require('node:path');

const SCHEMA_RE = /^[a-z][a-z0-9_]{0,50}$/;
const IDENTITY = { sessions: 'id', activity: 'id', app_events: 'seq', tg_notifications: 'id' };

/** SQLite dialect used by db.js and telegram/store.js -> PostgreSQL. All numbers are DOUBLE PRECISION, exactly like JS numbers. */
function translate(sql) {
  let s = sql.trim().replace(/;\s*$/, '');
  if (/^BEGIN IMMEDIATE$/i.test(s)) return { sql: 'BEGIN' };
  if (/^(CREATE|ALTER)\b/i.test(s)) {
    return { sql: s.replace(/INTEGER PRIMARY KEY AUTOINCREMENT/gi, 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY').replace(/\bINTEGER\b/g, 'DOUBLE PRECISION').replace(/\bREAL\b/g, 'DOUBLE PRECISION') };
  }
  s = s.replace(/\bAS ([a-z]+[A-Z]\w*)/g, 'AS "$1"');
  const ins = /^INSERT\s+(OR IGNORE |OR REPLACE )?INTO\s+(\w+)\s*\(([^)]*)\)/i.exec(s);
  let id = null;
  if (ins) {
    s = s.replace(/^INSERT\s+OR (IGNORE|REPLACE)\s+INTO/i, 'INSERT INTO');
    if (/IGNORE/i.test(ins[1] || '')) s += ' ON CONFLICT DO NOTHING';
    if (/REPLACE/i.test(ins[1] || '')) {
      const cols = ins[3].split(',').map((c) => c.trim());
      s += ` ON CONFLICT (${cols[0]}) DO UPDATE SET ${cols.slice(1).map((c) => `${c} = excluded.${c}`).join(', ')}`;
    }
    id = IDENTITY[ins[2].toLowerCase()] || null;
    if (id) s += ` RETURNING ${id} AS "rowid__"`;
  }
  let n = 0;
  s = s.replace(/'(?:[^']|'')*'|\?/g, (m) => (m === '?' ? `$${++n}` : m));
  return { sql: s, id };
}

const param = (x) => {
  if (x === undefined) throw new TypeError('undefined cannot be stored');
  if (typeof x === 'number' && !Number.isFinite(x)) return null; // as SQLite does for NaN
  if (typeof x === 'string') return x.includes('\u0000') ? x.split('\u0000').join('') : x;
  if (x === null || typeof x === 'number' || typeof x === 'bigint') return x;
  throw new TypeError(`cannot store a ${typeof x}`);
};

class PostgresSync {
  constructor(url, { schema, createSchema = false, dropOnClose = false, timeoutMs = 5000, onFatal = null }) {
    if (!SCHEMA_RE.test(schema)) throw new Error('Invalid schema name');
    Object.assign(this, { url, schema, timeoutMs, createSchema, dropOnClose });
    this.onFatal = onFatal || ((m) => { console.error(`[database] ${m}`); process.exit(1); });
    this.inTx = false;
    this.seq = 0;
    this.open();
  }

  open() {
    const sig = new Int32Array(new SharedArrayBuffer(4));
    const { port1, port2 } = new MessageChannel();
    const worker = new Worker(path.join(__dirname, 'db-postgres-worker.js'), { workerData: { port: port2, sig, url: this.url, schema: this.schema, createSchema: this.createSchema, timeoutMs: this.timeoutMs }, transferList: [port2], env: {} });
    worker.unref();
    worker.on('error', () => { /* reported to the caller as a timeout */ });
    this.link = { sig, port: port1, worker };
    try { this.call({ connect: true }, this.timeoutMs * 2); } catch (e) { this.dropLink(); throw e; }
  }

  dropLink() {
    const l = this.link;
    this.link = null;
    if (l) { try { l.port.close(); } catch { /* closed */ } l.worker.terminate(); }
  }

  call(msg, waitMs = this.timeoutMs + 2000) {
    const { sig, port } = this.link;
    const id = ++this.seq;
    const end = Date.now() + waitMs;
    port.postMessage({ ...msg, id });
    for (;;) {
      const v = Atomics.load(sig, 0);
      for (let m = receiveMessageOnPort(port); m; m = receiveMessageOnPort(port)) {
        if (m.message.id !== id) continue;
        if (!m.message.err) return m.message;
        throw Object.assign(new Error(m.message.err), { code: m.message.code, lost: m.message.lost });
      }
      const left = end - Date.now();
      if (left <= 0 || Atomics.wait(sig, 0, v, left) === 'timed-out') throw Object.assign(new Error('database timeout'), { lost: true });
    }
  }

  query(text, params = []) {
    const word = /^\s*(\w+)/.exec(text)[1].toUpperCase();
    if (!this.link) {
      if (word === 'ROLLBACK') { this.inTx = false; return { rows: [], count: 0 }; } // the server rolled back when the connection ended
      if (this.inTx) throw Object.assign(new Error('transaction lost'), { lost: true });
      this.open();
    }
    try {
      const r = this.call({ sql: text, params });
      if (word === 'BEGIN') this.inTx = true;
      if (word === 'COMMIT' || word === 'ROLLBACK') this.inTx = false;
      return r;
    } catch (e) {
      if (e.lost) {
        this.dropLink();
        // an autocommitted write or a COMMIT may or may not have happened
        if (word === 'COMMIT') { this.inTx = false; this.onFatal(`connection lost during COMMIT: ${e.message}`); }
        if (word === 'ROLLBACK') { this.inTx = false; return { rows: [], count: 0 }; } // the server rolls back by itself
      }
      if (e.code === '23505') e.message = `UNIQUE constraint failed: ${e.message}`;
      throw e;
    }
  }

  exec(sql) {
    // schema scripts contain no semicolons inside literals or bodies
    for (const part of sql.split(';')) if (part.trim()) this.query(translate(part).sql);
  }

  prepare(sql) {
    const t = translate(sql);
    const run = (args) => this.query(t.sql, args.map(param));
    return {
      get: (...a) => run(a).rows[0],
      all: (...a) => run(a).rows,
      run: (...a) => { const r = run(a); return { changes: r.count, lastInsertRowid: t.id && r.rows[0] ? r.rows[0].rowid__ : 0 }; },
    };
  }

  close() {
    if (!this.link) return;
    try { if (this.dropOnClose) this.query(`DROP SCHEMA ${this.schema} CASCADE`); this.call({ end: true }, 3000); } catch { /* closing anyway */ }
    this.dropLink();
  }
}

module.exports = { PostgresSync, translate };
